"""Time each stage and measure accuracy at several sizes.

    python bench/benchmark.py                   # 10k, 100k and 1M documents
    python bench/benchmark.py --sizes 50000     # one size

Writes bench/RESULTS.md. Peak memory is the process high-water mark, so read it as
"at most this much" for the largest size run so far.
"""

from __future__ import annotations

import argparse
import platform
import resource
import tempfile
import time
from pathlib import Path

import polars as pl

from recon2b import synth
from recon2b.loaders import load_books, load_gstr2b
from recon2b.matcher import reconcile
from recon2b.report import write_excel, write_flat


def peak_mb() -> float:
    kb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return kb / 1024 if platform.system() != "Darwin" else kb / (1024 * 1024)


def bench(n: int, workdir: Path, excel_limit: int) -> dict:
    paths = synth.write(workdir / f"n{n}", n, seed=42)
    t0 = time.perf_counter()
    books = load_books(paths["books"])
    t1 = time.perf_counter()
    portal = load_gstr2b(paths["gstr2b"])
    t2 = time.perf_counter()
    result = reconcile(books, portal)
    t3 = time.perf_counter()
    write_flat(result, workdir / f"n{n}.parquet")
    t4 = time.perf_counter()
    excel = None
    if n <= excel_limit:
        write_excel(result, workdir / f"n{n}.xlsx")
        excel = time.perf_counter() - t4
    score = synth.evaluate(
        result.rows, pl.read_csv(paths["truth_books"]), pl.read_csv(paths["truth_2b"])
    )
    return {
        "documents": n,
        "books_rows": books.height,
        "gstr2b_rows": portal.height,
        "load_books_s": t1 - t0,
        "load_2b_s": t2 - t1,
        "match_s": t3 - t2,
        "parquet_s": t4 - t3,
        "excel_s": excel,
        "precision": score["precision"],
        "recall": score["recall"],
        "peak_mb": peak_mb(),
        "passes": {k: v for k, v in result.timings.items()},
        "by_pass": score["by_pass"],
        "review": int(result.rows["needs_review"].sum()),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", type=int, nargs="+", default=[10_000, 100_000, 1_000_000])
    ap.add_argument("--excel-limit", type=int, default=100_000)
    ap.add_argument("--out", type=Path, default=Path(__file__).with_name("RESULTS.md"))
    args = ap.parse_args()

    results = []
    with tempfile.TemporaryDirectory() as tmp:
        for n in args.sizes:
            print(f"running {n:,} documents...", flush=True)
            r = bench(n, Path(tmp), args.excel_limit)
            results.append(r)
            print(
                f"  match {r['match_s']:.2f}s  precision {r['precision']:.2%}  "
                f"recall {r['recall']:.2%}  peak {r['peak_mb']:.0f} MB",
                flush=True,
            )

    lines = [
        "# Benchmark results",
        "",
        f"Machine: {platform.processor() or platform.machine()}, {_cpus()} cores, "
        f"Python {platform.python_version()}, Polars {pl.__version__}.",
        "Data: synthetic, generated by `recon2b synth` with the default noise levels.",
        "",
        "| Documents | Books rows | 2B rows | Load books | Load 2B | Match | Excel report "
        "| Precision | Recall | Peak memory |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in results:
        excel = f"{r['excel_s']:.1f} s" if r["excel_s"] is not None else "n/a, use .parquet"
        lines.append(
            f"| {r['documents']:,} | {r['books_rows']:,} | {r['gstr2b_rows']:,} "
            f"| {r['load_books_s']:.2f} s | {r['load_2b_s']:.2f} s | {r['match_s']:.2f} s "
            f"| {excel} | {r['precision']:.2%} | {r['recall']:.2%} | {r['peak_mb']:,.0f} MB |"
        )
    big = results[-1]
    lines += [
        "",
        f"## Where the time goes at {big['documents']:,} documents",
        "",
        "| Stage | Seconds |",
        "| --- | --- |",
    ]
    lines += [f"| {k} | {v:.2f} |" for k, v in big["passes"].items()]
    lines += [
        "",
        f"## Pairs made by each pass at {big['documents']:,} documents",
        "",
        "| Pass | Pairs | Correct | Precision |",
        "| --- | --- | --- | --- |",
    ]
    for rec in big["by_pass"].iter_rows(named=True):
        lines.append(
            f"| {rec['match_pass']} | {rec['pairs']:,} | {rec['correct']:,} "
            f"| {rec['precision']:.2%} |"
        )
    lines += ["", f"{big['review']:,} pairs were sent to the Review sheet at this size."]
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


def _cpus() -> int:
    import os

    return os.cpu_count() or 1


if __name__ == "__main__":
    main()
